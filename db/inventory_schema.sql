-- ----------------------------------------------------------------
-- 1. INV_CATEGORIES – Termékkategóriák
-- ----------------------------------------------------------------
CREATE TABLE INV_CATEGORIES (
    category_id     VARCHAR(20)  NOT NULL,
    category_name   VARCHAR(100) NOT NULL,
    description     VARCHAR(255),
    CONSTRAINT pk_inv_categories PRIMARY KEY (category_id)
);

-- ----------------------------------------------------------------
-- 2. INV_SUPPLIERS – Szállítók
-- ----------------------------------------------------------------
CREATE TABLE INV_SUPPLIERS (
    supplier_id       VARCHAR(20)   NOT NULL,
    supplier_name     VARCHAR(150)  NOT NULL,
    contact_email     VARCHAR(150),
    default_lead_days INTEGER       NOT NULL DEFAULT 14,
    reliability_score DECIMAL(5,2)  NOT NULL DEFAULT 80.0,
    CONSTRAINT pk_inv_suppliers PRIMARY KEY (supplier_id)
);

-- ----------------------------------------------------------------
-- 3. INV_PRODUCTS – Termékek (törzstábla)
-- ----------------------------------------------------------------
CREATE TABLE INV_PRODUCTS (
    product_id       VARCHAR(20)    NOT NULL,
    product_code     VARCHAR(50)    NOT NULL,
    product_name     VARCHAR(200)   NOT NULL,
    category_id      VARCHAR(20)    NOT NULL,
    unit             VARCHAR(30)    NOT NULL,
    unit_price       DECIMAL(12,2)  NOT NULL,
    supplier_id      VARCHAR(20)    NOT NULL,
    lead_time_days   INTEGER        NOT NULL,
    min_stock_level  DECIMAL(12,2)  NOT NULL,
    max_stock_level  DECIMAL(12,2)  NOT NULL,
    reorder_quantity DECIMAL(12,2)  NOT NULL,
    active           BOOLEAN        DEFAULT TRUE,
    CONSTRAINT pk_inv_products     PRIMARY KEY (product_id),
    CONSTRAINT uq_product_code     UNIQUE (product_code),
    CONSTRAINT fk_prod_category    FOREIGN KEY (category_id) REFERENCES INV_CATEGORIES(category_id),
    CONSTRAINT fk_prod_supplier    FOREIGN KEY (supplier_id) REFERENCES INV_SUPPLIERS(supplier_id)
);

-- ----------------------------------------------------------------
-- 4. INV_STOCK_MOVEMENTS – Készletmozgások naplója
--    quantity: POZITÍV = bevételezés (IN/RETURN), NEGATÍV = kiadás (OUT)
-- ----------------------------------------------------------------
CREATE TABLE INV_STOCK_MOVEMENTS (
    movement_id   INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    product_id    VARCHAR(20)   NOT NULL,
    movement_date DATE          NOT NULL,
    quantity      DECIMAL(12,2) NOT NULL,
    movement_type VARCHAR(20)   NOT NULL,
    reference_doc VARCHAR(100),
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inv_movements     PRIMARY KEY (movement_id),
    CONSTRAINT fk_mov_product       FOREIGN KEY (product_id) REFERENCES INV_PRODUCTS(product_id),
    CONSTRAINT chk_movement_type    CHECK (movement_type IN ('IN','OUT','RETURN','ADJUSTMENT'))
);

-- Teljesítményindex a leggyakoribb lekérdezési mintákhoz
CREATE INDEX idx_inv_mov_prod_date ON INV_STOCK_MOVEMENTS (product_id, movement_date);
CREATE INDEX idx_inv_mov_type_date ON INV_STOCK_MOVEMENTS (movement_type, movement_date);

-- ----------------------------------------------------------------
-- 5. INV_CURRENT_STOCK – Aktuális készletszintek (pillanatkép)
-- ----------------------------------------------------------------
CREATE TABLE INV_CURRENT_STOCK (
    product_id       VARCHAR(20)   NOT NULL,
    current_quantity DECIMAL(12,2) NOT NULL,
    warehouse_zone   VARCHAR(20),
    last_updated     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inv_current_stock PRIMARY KEY (product_id),
    CONSTRAINT fk_stock_product     FOREIGN KEY (product_id) REFERENCES INV_PRODUCTS(product_id)
);

